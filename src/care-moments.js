const dayOf = (date) => Date.parse(date + 'T00:00:00Z') / 86400000;
export function normalizePresence(date, together, slots) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) throw new Error('Data non valida');
  if (!together) return { date, together:false, slots:[] };
  const known = new Set(SLOTS.map(s=>s.id));
  const selected = [...new Set(slots || [])].filter(s=>known.has(s));
  if (!selected.length) throw new Error('Indica almeno un momento insieme');
  return { date, together:true, slots:selected };
}
export function togetherToday(presence, date) {
  return presence?.date===date && presence.together===true && presence.slots?.length>0;
}
export function hypotheticalStage(record, date) {
  // Withdrawal bleeding is NOT a natural ovulatory cycle. Used only for optional suggestion categories.
  if (!record?.consent || !record?.regular || !record?.cycleDays || !record?.lastStart) return 'any';
  const diff = Math.floor(dayOf(date)-dayOf(record.lastStart));
  if (!Number.isFinite(diff) || diff<0 || diff>2*record.cycleDays) return 'any';
  const d = diff % record.cycleDays;
  if (d < record.periodDays) return 'bleed';
  if (d >= record.cycleDays-4) return 'pre';
  if (d <= record.periodDays+5) return 'after';
  return 'any';
}
export function suggestionFor(date, slot, who='together', stage='any', ordinal=0) {
  const candidates=MOMENTS.filter(x=>x.who===who && x.slot===slot && (x.stage==='any'||x.stage===stage));
  const pool=candidates.length?candidates:MOMENTS.filter(x=>x.who===who && x.stage==='any');
  if(!pool.length)return null;
  return pool[((ordinal%pool.length)+pool.length)%pool.length];
}
export function choiceForPresence(presence,date,record,confirmedDates=[],afterMinute=-1) {
  if (!togetherToday(presence,date)) return null;
  const slot=SLOTS.filter(x=>presence.slots.includes(x.id)&&x.minute>afterMinute)
    .sort((a,b)=>a.minute-b.minute)[0]?.id;
  if (!slot) return null;
  const stage=hypotheticalStage(record,date);
  const ordinal=confirmedDates.filter(x=>x<date).length;
  return { slot, stage, moment:suggestionFor(date,slot,'together',stage,ordinal) };
}
